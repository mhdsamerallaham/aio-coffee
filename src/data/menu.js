// Safe helper to resolve bilingual string or object
const safeResolve = (val, lang) => {
  if (!val) return '';
  if (typeof val === 'string') return val;
  if (typeof val === 'object') {
    return val[lang] || val.en || val.tr || '';
  }
  return String(val);
};

export const getLocalizedCategory = (cat, lang = 'tr') => {
  if (!cat) return null;
  return {
    ...cat,
    name: safeResolve(cat.name, lang),
    shortName: safeResolve(cat.shortName, lang),
    subtitle: safeResolve(cat.subtitle, lang),
    badge: safeResolve(cat.badge, lang),
  };
};

export const getLocalizedOptionGroups = (product, lang = 'tr') => {
  if (!product) return [];
  if (Array.isArray(product.optionGroups) && product.optionGroups.length > 0) {
    return product.optionGroups.map((group) => ({
      ...group,
      name: safeResolve(group.name, lang),
      options: (group.options || []).map((opt) => ({
        ...opt,
        name: safeResolve(opt.name, lang),
      })),
    }));
  }

  const syntheticGroups = [];

  if (product.sizes && product.sizes.length > 1) {
    syntheticGroups.push({
      id: 'size_selection',
      name: lang === 'tr' ? 'Boyut Seçimi' : 'Size Selection',
      required: true,
      type: 'single',
      options: product.sizes.map((s, idx) => ({
        id: `size_${idx}`,
        name: safeResolve(s.name, lang),
        price: Number(s.price || 0),
      })),
    });
  }

  if (product.extras && product.extras.length > 0) {
    const milks = [];
    const syrups = [];
    const others = [];

    product.extras.forEach((ex) => {
      const nameTr = safeResolve(ex.name, 'tr').toLowerCase();
      if (nameTr.includes('süt') || nameTr.includes('milk')) {
        milks.push(ex);
      } else if (nameTr.includes('şurup') || nameTr.includes('syrup')) {
        syrups.push(ex);
      } else {
        others.push(ex);
      }
    });

    if (milks.length > 0) {
      syntheticGroups.push({
        id: 'milk_selection',
        name: lang === 'tr' ? 'Süt Seçimi' : 'Milk Selection',
        required: false,
        type: 'single',
        options: milks.map((m, idx) => ({
          id: `milk_${idx}`,
          name: safeResolve(m.name, lang),
          price: Number(m.price || 0),
        })),
      });
    }

    if (syrups.length > 0) {
      syntheticGroups.push({
        id: 'syrup_selection',
        name: lang === 'tr' ? 'Şurup Seçimi' : 'Syrup Selection',
        required: false,
        type: 'multiple',
        options: syrups.map((e, idx) => ({
          id: `syrup_${idx}`,
          name: safeResolve(e.name, lang),
          price: Number(e.price || 0),
        })),
      });
    }

    if (others.length > 0) {
      syntheticGroups.push({
        id: 'extras_selection',
        name: lang === 'tr' ? 'Ekstra & Şot Seçimi' : 'Extras & Shot Selection',
        required: false,
        type: 'multiple',
        options: others.map((e, idx) => ({
          id: `extra_${idx}`,
          name: safeResolve(e.name, lang),
          price: Number(e.price || 0),
        })),
      });
    }
  }

  return syntheticGroups;
};

export const getLocalizedProduct = (product, lang = 'tr') => {
  if (!product) return null;
  return {
    ...product,
    name: safeResolve(product.name, lang),
    description: safeResolve(product.description, lang),
    sizes: (product.sizes || []).map((s) => ({
      ...s,
      name: safeResolve(s.name, lang),
    })),
    extras: (product.extras || []).map((e) => ({
      ...e,
      name: safeResolve(e.name, lang),
    })),
    optionGroups: getLocalizedOptionGroups(product, lang),
  };
};

